Future<Map<String, String>> _titleKeys(Directory user, String relative) async {
  final file = await addonFile(user, relative);
  if (!await file.exists()) return {};
  if (await file.length() > 2 * 1024 * 1024)
    throw const FormatException('Private Switch title keys exceed their limit');
  final text = await file.readAsString();
  validateSwitchKeyFile(text, prod: false);
  return {
    for (final line in const LineSplitter().convert(text))
      if (RegExp(r'^\s*[a-fA-F0-9]{32}\s*=').hasMatch(line))
        line.split('=').first.trim().toLowerCase(): line
            .split('=')
            .last
            .trim()
            .toLowerCase(),
  };
}

/// File policy, title association and publication stay in Dart. Native NCA
/// payloads remain encrypted and Eden consumes its own CNMT/content format.
Future<String> stageEdenContent(
  File game,
  Iterable<(File, String)> packages,
  Directory profile,
  Directory payload,
  Map<String, dynamic> units,
  int version,
  DownloadCancellation cancellation,
) async {
  final user = Directory('${profile.path}/data/eden'),
      key = await switchHeaderKey(await addonFile(user, 'keys/prod.keys'));
  try {
    final base = await switchBaseIdentity(game, key),
        baseValue = int.parse(base, radix: 16),
        known = await _titleKeys(user, 'keys/title.keys'),
        generated = await _titleKeys(user, 'keys/title.keys_autogenerated');
    for (final e in generated.entries) {
      if (known[e.key] != null && known[e.key] != e.value)
        throw const FormatException(
          'Conflicting private Switch title keys were kept',
        );
      known[e.key] = e.value;
    }
    final additions = <String, String>{}, requiredRights = <String>{};
    var updatePackages = 0, extractedBytes = 0;
    for (final input in packages) {
      cancellation.check();
      if (input.$2 == 'update' && ++updatePackages > 1)
        throw const FormatException(
          'Eden currently accepts one update NSP per game. Keep the intended update in RomM; existing content was kept.',
        );
      final entries = await switchArchiveEntries(input.$1),
          ncas = <SwitchArchiveEntry>[],
          metadata = <SwitchNcaHeader>[];
      final io = await input.$1.open();
      try {
        for (final e in entries) {
          cancellation.check();
          final name = e.name.toLowerCase();
          if (name.endsWith('.nca')) {
            if (!RegExp(r'^[a-f0-9]{32}(?:\.cnmt)?\.nca$').hasMatch(name))
              throw const FormatException(
                'Switch NCA has no native content ID',
              );
            final h = await switchNcaHeader(input.$1, e, key),
                id = int.parse(h.title, radix: 16);
            final matches = input.$2 == 'update'
                ? (id == baseValue || id == baseValue + 0x800)
                : input.$2 == 'dlc' &&
                      (id & ~0x1fff) == baseValue &&
                      id >= baseValue + 0x1000;
            if (!matches)
              throw const FormatException(
                'Eden package contains content for another game. Existing files were kept.',
              );
            if (h.type == 1) metadata.add(h);
            if (h.rights != '0' * 32) requiredRights.add(h.rights);
            ncas.add(e);
          } else if (name.endsWith('.tik')) {
            if (e.bytes < 4 || e.bytes > 4096)
              throw const FormatException('Invalid Switch ticket');
            final b = await switchRead(
              io,
              await io.length(),
              e.offset,
              e.bytes,
            );
            final signature = ByteData.sublistView(b)
                    .getUint32(0, Endian.little),
                start = switch (signature) {
                  0x10000 || 0x10003 => 0x240,
                  0x10001 || 0x10004 => 0x140,
                  0x10002 || 0x10005 => 0x80,
                  _ => -1,
                };
            if (start < 0 || b.length < start + 0x170)
              throw const FormatException('Unsupported Switch ticket');
            if (b[start + 0x141] != 0)
              continue; // Personalized tickets need the owner's key.
            String hex(int at, int length) => b
                .sublist(at, at + length)
                .map((n) => n.toRadixString(16).padLeft(2, '0'))
                .join();
            final rights = hex(start + 0x160, 16),
                value = hex(start + 0x40, 16),
                id = int.parse(rights.substring(0, 16), radix: 16);
            if ((id & ~0x1fff) != baseValue)
              throw const FormatException(
                'Switch ticket belongs to another game',
              );
            if ((known[rights] != null && known[rights] != value) ||
                (additions[rights] != null && additions[rights] != value))
              throw const FormatException(
                'Conflicting Switch ticket keys were kept',
              );
            additions[rights] = value;
          }
        }
      } finally {
        await io.close();
      }
      if (ncas.isEmpty ||
          metadata.isEmpty ||
          input.$2 == 'update' &&
              !metadata.any(
                (h) =>
                    h.title ==
                    (baseValue + 0x800).toRadixString(16).padLeft(16, '0'),
              ))
        throw const FormatException(
          'Switch package has no matching native content metadata',
        );
      for (final e in ncas) {
        final relative =
            'nand/user/Contents/registered/${e.name.toLowerCase().substring(0, 32)}.nca';
        final target = await addonFile(payload, relative, createParents: true),
            existing = units[relative] as Map?;
        if (existing == null) {
          extractedBytes += e.bytes;
          if (units.length >= 100000 ||
              extractedBytes > 128 * 1024 * 1024 * 1024)
            throw const FormatException(
              'Switch content exceeds its installation limit',
            );
          await target.create(exclusive: true);
        }
        final out = existing == null
                ? await target.open(mode: FileMode.writeOnly)
                : null,
            digest = ProgressDigest.sha256();
        var bytes = 0;
        try {
          await for (final chunk in input.$1.openRead(
            e.offset,
            e.offset + e.bytes,
          )) {
            cancellation.check();
            bytes += chunk.length;
            digest.add(chunk);
            if (out != null) await out.writeFrom(chunk);
          }
          await out?.flush();
        } finally {
          await out?.close();
        }
        final hash = digest.finish();
        if (bytes != e.bytes ||
            !hash.startsWith(e.name.substring(0, 32).toLowerCase()) ||
            (existing != null
                ? (existing['files'] as Map)[''] != hash
                : await progressFileHash(target) != hash))
          throw const FormatException(
            'Switch NCA bytes do not match their native content ID',
          );
        if (existing != null) continue;
        units[relative] = {
          'version': version,
          'files': {'': hash},
        };
      }
    }
    if (requiredRights.any(
      (r) => !known.containsKey(r) && !additions.containsKey(r),
    ))
      throw const FormatException(
        'A Switch package needs title keys not present in the configured files or a supported common ticket. Existing content was kept.',
      );
    // Native-generated title keys are configuration, not deletable game progress.
    // Preserve existing keys and publish one merged file under the session lease.
    final fresh = {
      for (final e in additions.entries)
        if (!known.containsKey(e.key)) e.key: e.value,
    };
    if (fresh.isNotEmpty) {
      final file = await addonFile(
            user,
            'keys/title.keys_autogenerated',
            createParents: true,
          ),
          text = await file.exists() ? await file.readAsString() : '';
      final merged =
          '$text\n${fresh.entries.map((e) => '${e.key} = ${e.value}').join('\n')}\n';
      validateSwitchKeyFile(merged, prod: false);
      await ownedDirectory(file.parent);
      await atomicText(file.path, merged);
      final verified = await _titleKeys(user, 'keys/title.keys_autogenerated');
      if (fresh.entries.any((e) => verified[e.key] != e.value))
        throw const FileSystemException(
          'Private Switch ticket readback failed',
        );
    }
    return base;
  } finally {
    key.fillRange(0, key.length, 0);
  }
}
